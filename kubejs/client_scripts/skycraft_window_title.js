const skyCraftTip = skyCraftTips[Math.floor(Math.random() * skyCraftTips.length)];
let skyCraftTitleLogged = false;
let skyCraftTitleErrorLogged = false;

function applySkyCraftWindowTitle() {
  const title = skyCraftTitleBase + " tips:" + skyCraftTip;
  Java.loadClass("net.minecraft.client.Minecraft").getInstance().getWindow().setTitle(title);
  if (!skyCraftTitleLogged) {
    skyCraftTitleLogged = true;
    console.info("[天工创世] 窗口标题已更新：" + title);
  }
}

function tryApplySkyCraftWindowTitle() {
  try {
    applySkyCraftWindowTitle();
  } catch (error) {
    if (!skyCraftTitleErrorLogged) {
      skyCraftTitleErrorLogged = true;
      console.error("[天工创世] 设置窗口标题失败：" + error);
    }
  }
}

// 先覆盖启动加载界面；CustomWindowTitle 若随后重置，客户端 tick 会继续恢复。
tryApplySkyCraftWindowTitle();

// 客户端 tick 晚于 CustomWindowTitle 初始化；首次立即恢复，此后每 5 秒校验一次。
let skyCraftTitleTickCounter = 0;
ClientEvents.tick(event => {
  skyCraftTitleTickCounter++;
  if (skyCraftTitleTickCounter === 1 || skyCraftTitleTickCounter % 100 === 0) {
    tryApplySkyCraftWindowTitle();
  }
});

// 进入世界时立即再补一次，避免加载界面切换时被其他模组重置。
ClientEvents.loggedIn(event => tryApplySkyCraftWindowTitle());
